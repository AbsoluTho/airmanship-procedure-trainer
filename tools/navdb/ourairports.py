"""Build js/data/world.js from OurAirports (public domain): Saudi airports, runways and navaids.

Usage (from the repository root):
    python3 tools/navdb/ourairports.py [CSV_DIR]
CSV_DIR must hold airports.csv, runways.csv and navaids.csv from
https://github.com/davidmegginson/ourairports-data (downloaded there if missing).

OurAirports is community data: good enough for a procedure trainer, never for navigation.
Airports already typed from charts in navdb.js keep their chart elevation, variation and
runway courses; only their runway threshold positions are taken from OurAirports."""
import csv, json, math, os, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'tools', 'navdb', 'ourairports')
URL = 'https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/'
COUNTRY = 'SA'
NAV_TYPES = {'VOR', 'VOR-DME', 'VORTAC', 'DME', 'NDB', 'NDB-DME', 'TACAN'}

def load(name):
    p = os.path.join(SRC, name)
    if not os.path.exists(p):
        os.makedirs(SRC, exist_ok=True)
        urllib.request.urlretrieve(URL + name, p)
    with open(p, encoding='utf-8') as f:
        return list(csv.DictReader(f))

def fnum(v, d=None):
    try: return float(v)
    except (TypeError, ValueError): return d

def dest(lat, lon, brg, nm):
    r = nm / 60 * math.pi / 180; t = math.radians(brg); l1 = math.radians(lat); o1 = math.radians(lon)
    l2 = math.asin(math.sin(l1) * math.cos(r) + math.cos(l1) * math.sin(r) * math.cos(t))
    o2 = o1 + math.atan2(math.sin(t) * math.sin(r) * math.cos(l1), math.cos(r) - math.sin(l1) * math.sin(l2))
    return [round(math.degrees(l2), 5), round(math.degrees(o2), 5)]

def gc(a, b):
    l1, o1, l2, o2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    return math.degrees(math.acos(min(1, math.sin(l1) * math.sin(l2) + math.cos(l1) * math.cos(l2) * math.cos(o2 - o1)))) * 60

airports = [a for a in load('airports.csv') if a['iso_country'] == COUNTRY and a['type'] in ('large_airport', 'medium_airport')
            and len(a['ident']) == 4 and a['ident'].startswith('OE')]
navs = [n for n in load('navaids.csv') if n['iso_country'] == COUNTRY and n['type'] in NAV_TYPES]
runways = load('runways.csv')

nav_out = {}
for n in navs:
    pos = [round(float(n['latitude_deg']), 5), round(float(n['longitude_deg']), 5)]
    khz = fnum(n['frequency_khz'])
    freq = (round(khz / 1000, 2) if n['type'] not in ('NDB', 'NDB-DME') else int(khz)) if khz else None
    nav_out.setdefault(n['ident'], {'type': n['type'], 'pos': pos, 'freq': freq, 'var': fnum(n['magnetic_variation_deg'], 0),
                                    'name': n['name'], 'apt': n['associated_airport'] or None})

def var_at(pos):
    vs = [(gc(pos, v['pos']), v['var']) for v in nav_out.values() if v['var']]
    return round(min(vs)[1]) if vs else 3

apt_out = {}
for a in airports:
    pos = [round(float(a['latitude_deg']), 5), round(float(a['longitude_deg']), 5)]
    var = var_at(pos)
    rw = {}
    for r in runways:
        if r['airport_ident'] != a['ident'] or r['closed'] == '1': continue
        L = fnum(r['length_ft'])
        for e, o in (('le', 'he'), ('he', 'le')):
            ident, lat, lon, hdg = r[e + '_ident'], fnum(r[e + '_latitude_deg']), fnum(r[e + '_longitude_deg']), fnum(r[e + '_heading_degT'])
            if not ident or lat is None or lon is None or hdg is None: continue
            p = [round(lat, 5), round(lon, 5)]
            disp = fnum(r[e + '_displaced_threshold_ft'], 0)
            if disp: p = dest(lat, lon, hdg, disp * 0.3048 / 1852)
            d = {'pos': p, 'len': round((L - disp) * 0.3048) if L else 3000, 'crs': round(hdg - var) % 360 or 360}
            el = fnum(r[e + '_elevation_ft'])
            if el is not None: d['tdze'] = round(el)
            rw[ident] = d
    if not rw: continue
    apt_out[a['ident']] = {'pos': pos, 'elev': round(fnum(a['elevation_ft'], 0)), 'var': var, 'rwy': rw, 'name': a['name']}

out = os.path.join(ROOT, 'js', 'data', 'world.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write("'use strict';\n/* Generated by tools/navdb/ourairports.py from OurAirports (public domain). Do not edit by hand.\n"
            "   Community data for training only: never use for navigation. */\n")
    f.write('const OA_APT=' + json.dumps(apt_out, separators=(',', ':')) + ';\n')
    f.write('const OA_NAV=' + json.dumps(nav_out, separators=(',', ':')) + ';\n')
    f.write('''/* merge: chart-typed airports keep elevation, variation and runway courses; threshold positions come from OurAirports */
(function(){for(const[id,a]of Object.entries(OA_APT)){const c=DB.apt[id];
  if(!c){DB.apt[id]={pos:a.pos,elev:a.elev,var:a.var,rwy:a.rwy,name:a.name};continue}
  c.name=a.name;for(const[r,o]of Object.entries(a.rwy)){if(c.rwy[r]){c.rwy[r].pos=o.pos;if(c.rwy[r].tdze==null&&o.tdze!=null)c.rwy[r].tdze=o.tdze}else c.rwy[r]=Object.assign({},o,{crs:o.crs})}}
  DB.nav=OA_NAV})();
''')
print(out, len(apt_out), 'airports', sum(len(a['rwy']) for a in apt_out.values()), 'runway ends', len(nav_out), 'navaids')
